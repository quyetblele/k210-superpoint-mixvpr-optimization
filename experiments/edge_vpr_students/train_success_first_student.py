"""Resumable long-stage training for the screened success-first SQ240 student.

GT1 is intentionally absent.  Each stage consumes an immutable supervised
place index and a bank generated by the already-frozen strong MixVPR teacher.
"""
from __future__ import annotations

import argparse
import json
import random
import sqlite3
import sys
from pathlib import Path

import numpy as np
import torch
import torch.nn.functional as F
from torch.autograd.graph import save_on_cpu

ROOT = Path("/home/quyet/k210_lab")
sys.path.insert(0, str(ROOT / "experiments" / "edge_vpr_students"))
import success_first_train_core as core
from per_image_teacher import PerImageTeacher, POLICY


def load_bank(directory: Path):
    manifest = json.loads((directory / "manifest.json").read_text())
    database = sqlite3.connect(manifest["bank"])
    descriptors = np.load(manifest["descriptors"], mmap_mode="r")
    descriptor_rows = database.execute("SELECT place_id,path,offset FROM descriptors").fetchall()
    offsets = {path: offset for _, path, offset in descriptor_rows}
    # The compact bank stores one frozen-teacher representative per place.
    # Training plans may sample any other view of that place, so KD deliberately
    # uses the immutable place prototype instead of silently failing or
    # regenerating a stochastic teacher target.
    place_offsets = {place: offset for place, _, offset in descriptor_rows}
    neighbors: dict[str, list[str]] = {}
    for place, _, negative in database.execute(
        "SELECT place_id,rank,negative_place_id FROM hard_neighbors ORDER BY place_id,rank"
    ):
        neighbors.setdefault(place, []).append(negative)
    database.close()
    return manifest, descriptors, offsets, place_offsets, neighbors


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--identity", choices=("A_C144_H112", "B_C160_H96"), required=True)
    parser.add_argument("--stage", required=True)
    parser.add_argument("--steps", type=int, required=True)
    parser.add_argument("--database", type=Path, required=True)
    parser.add_argument("--dev-database", type=Path)
    parser.add_argument("--bank", type=Path, required=True)
    parser.add_argument("--init", type=Path)
    parser.add_argument("--resume", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--eval-every", type=int, default=500)
    parser.add_argument("--plan-chunk", type=int, default=250)
    parser.add_argument("--physical-places", type=int, default=4)
    parser.add_argument("--accumulation", type=int, default=8)
    parser.add_argument("--views-per-place", type=int, default=4)
    args = parser.parse_args()

    device = core.require_cuda(); args.output.mkdir(parents=True, exist_ok=True)
    index = core.PlaceIndex(args.database)
    dev_index = core.PlaceIndex(args.dev_database or args.database)
    bank_manifest, bank_descriptors, offsets, place_offsets, neighbors = load_bank(args.bank)
    targets = PerImageTeacher(core.ROOT/'artifacts/success_first/per_image_teacher',device)
    random.seed(core.SEED); np.random.seed(core.SEED)
    torch.manual_seed(core.SEED); torch.cuda.manual_seed_all(core.SEED)
    model = core.build_student(args.identity).to(device)
    if args.init:
        initial = torch.load(args.init, map_location="cpu", weights_only=False)
        model.load_state_dict(initial["model_state_dict"], strict=True)
    optimizer = torch.optim.AdamW(model.parameters(), lr=3e-4, weight_decay=1e-4)
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=args.steps, eta_min=3e-5)
    if not torch.cuda.is_bf16_supported():
        raise RuntimeError('BF16 GPU support required for this training recipe')
    scaler = torch.amp.GradScaler("cuda", enabled=False)
    state = {"optimizer_step": 0, "best_key": [-1.0, -1.0, -1e9], "best_metrics": None,
             "trace": []}
    if args.resume:
        checkpoint = torch.load(args.resume, map_location="cpu", weights_only=False)
        if checkpoint.get('precision') != 'bf16_forward_fp32_norm_loss':
            raise RuntimeError('incompatible resume precision')
        if checkpoint.get('teacher_target_policy') != POLICY:
            raise RuntimeError('incompatible teacher targets in resume checkpoint')
        if checkpoint["identity"] != args.identity or checkpoint["stage"] != args.stage:
            raise RuntimeError("resume identity/stage mismatch")
        model.load_state_dict(checkpoint["model_state_dict"])
        optimizer.load_state_dict(checkpoint["optimizer_state_dict"])
        scheduler.load_state_dict(checkpoint["scheduler_state_dict"])
        scaler.load_state_dict(checkpoint["scaler_state_dict"])
        state = checkpoint["cursor"]
        core.restore_rng(checkpoint["rng_state"])

    if state["optimizer_step"] == 0 and state["best_metrics"] is None:
        baseline = core.dev_metrics(model, dev_index, 240, device, max_places=1000)
        state["best_metrics"] = baseline
        state["best_key"] = [baseline["R@1"], baseline["R@5"],
                             baseline["positive_hardest_negative_margin"]]
        core.atomic_torch(args.output / "best.pt", {"model_state_dict": model.state_dict(),
            "identity": args.identity, "stage": args.stage, "step": 0,
            "dev_metrics": baseline, "strong_teacher_sha256": bank_manifest["teacher_checkpoint_sha256"]})

    accumulation = args.accumulation
    while state["optimizer_step"] < args.steps:
        chunk_start = (state["optimizer_step"] // args.plan_chunk) * args.plan_chunk
        chunk_end = min(chunk_start + args.plan_chunk, args.steps)
        plan_path = args.output / f"plan_{chunk_start:06d}_{chunk_end:06d}.pt"
        if not plan_path.exists():
            stage_seed = int.from_bytes(args.stage.encode()[:4].ljust(4, b"_"), "little")
            plan = core.make_plan(index, (chunk_end - chunk_start) * accumulation,
                                  core.SEED + stage_seed + chunk_start,
                                  views=args.views_per_place,
                                  places_per_step=args.physical_places, hard_neighbors=neighbors)
            core.atomic_torch(plan_path, {"schema_version": 1, "stage": args.stage,
                "start_step": chunk_start, "end_step": chunk_end, "accumulation": accumulation,
                "teacher_bank_sha256": core.sha256(args.bank / "manifest.json"), "plan": plan})
        payload = torch.load(plan_path, map_location="cpu", weights_only=False)
        plan = payload["plan"]
        expected = (chunk_end - chunk_start) * accumulation
        if len(plan) != expected:
            raise RuntimeError("persisted student plan length mismatch")

        resume_step = state["optimizer_step"]
        local_start = (resume_step - chunk_start) * accumulation
        model.train()
        for optimizer_step in range(resume_step, chunk_end):
            optimizer.zero_grad(set_to_none=True)
            sums = {key: 0.0 for key in ("task", "ranking_kd", "relational_kd", "confidence", "margin")}
            base = local_start + (optimizer_step - resume_step) * accumulation
            for micro in range(accumulation):
                item = plan[base + micro]
                images, labels = core.batch_from_plan(item, 240, device)
                teacher = targets.targets(item['samples'])
                with save_on_cpu(pin_memory=False):
                    with torch.amp.autocast("cuda", dtype=torch.bfloat16):
                        student = model.raw(images)
                    with torch.amp.autocast('cuda', enabled=False):
                        student = F.normalize(student.float(),dim=1)
                        task = core.retrieval_loss(student, labels)
                        ranking, confidence, margin = core.ranking_kd(student, teacher, labels)
                        relational = F.mse_loss(student @ student.T, teacher @ teacher.T)
                        total = (task + ranking + 2.0 * relational) / accumulation
                if not torch.isfinite(total):
                    raise RuntimeError(f"non-finite student loss at step {optimizer_step}")
                scaler.scale(total).backward()
                for key, value in (("task", task), ("ranking_kd", ranking),
                                   ("relational_kd", relational), ("confidence", confidence),
                                   ("margin", margin)):
                    sums[key] += float(value.detach()) / accumulation
            scaler.unscale_(optimizer)
            grad_norm = torch.nn.utils.clip_grad_norm_(model.parameters(), 10.0)
            if not torch.isfinite(grad_norm):
                raise RuntimeError(f"non-finite student gradient at step {optimizer_step}")
            scaler.step(optimizer); scaler.update(); scheduler.step()
            state["optimizer_step"] = optimizer_step + 1
            state["trace"].append({"step": optimizer_step + 1, **sums,
                                   "grad_norm": float(grad_norm),
                                   "lr": optimizer.param_groups[0]["lr"]})

            if state["optimizer_step"] % args.eval_every == 0 or state["optimizer_step"] == args.steps:
                metrics = core.dev_metrics(model, dev_index, 240, device, max_places=1000)
                key = [metrics["R@1"], metrics["R@5"], metrics["positive_hardest_negative_margin"]]
                if key > state["best_key"]:
                    state["best_key"] = key; state["best_metrics"] = metrics
                    core.atomic_torch(args.output / "best.pt", {"model_state_dict": model.state_dict(),
                        "identity": args.identity, "stage": args.stage, "step": state["optimizer_step"],
                        "dev_metrics": metrics, "strong_teacher_sha256": bank_manifest["teacher_checkpoint_sha256"]})
                model.train()

            checkpoint = {"schema_version": 2, "identity": args.identity, "stage": args.stage,
                "precision": "bf16_forward_fp32_norm_loss",
                "teacher_target_policy": POLICY, "teacher_contract": targets.contract,
                "model_state_dict": model.state_dict(), "optimizer_state_dict": optimizer.state_dict(),
                "scheduler_state_dict": scheduler.state_dict(), "scaler_state_dict": scaler.state_dict(),
                "cursor": state, "rng_state": core.rng_state(), "plan_path": str(plan_path),
                "plan_sha256": core.sha256(plan_path), "strong_teacher_sha256": bank_manifest["teacher_checkpoint_sha256"],
                "config": {"steps": args.steps, "input": [240, 240], "descriptor_dim": 512,
                           "physical_places": args.physical_places,
                           "accumulation": accumulation,
                           "effective_places": args.physical_places * accumulation,
                           "effective_images": args.physical_places * accumulation * args.views_per_place,
                           "views_per_place": args.views_per_place,
                           "teacher_target": POLICY,
                           "database": str(args.database), "gt1_used": False}}
            if state["optimizer_step"] % 50 == 0 or state["optimizer_step"] == args.steps:
                core.atomic_torch(args.output / "latest.pt", checkpoint)

    final = args.output / "final.pt"; core.atomic_torch(final, checkpoint)
    report = {"status": "COMPLETE", "identity": args.identity, "stage": args.stage,
              "optimizer_steps": state["optimizer_step"], "best_metrics": state["best_metrics"],
              "best_checkpoint": str(args.output / "best.pt"), "final_checkpoint": str(final),
              "final_sha256": core.sha256(final), "strong_teacher_sha256": bank_manifest["teacher_checkpoint_sha256"],
              "gt1_used": False}
    core.atomic_json(args.output / "report.json", report); print(json.dumps(report))


if __name__ == "__main__":
    main()
